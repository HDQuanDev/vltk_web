import { z } from "zod";
const vec = z.object({ x: z.number().finite(), y: z.number().finite() });
const item = z.object({
  id: z.string().min(1),
  definitionId: z.string(),
  quantity: z.number().int().min(1).max(99),
});
const entity = vec.extend({
  id: z.string(),
  kind: z.enum(["player", "monster"]),
  definitionId: z.string(),
  name: z.string(),
  mapId: z.string(),
  level: z.number().int().min(1).max(60),
  hp: z.number().nonnegative(),
  mp: z.number().nonnegative(),
  maxHp: z.number().positive(),
  maxMp: z.number().nonnegative(),
  attack: z.number().nonnegative(),
  defense: z.number().nonnegative(),
  element: z.enum(["metal", "wood", "water", "fire", "earth"]),
  path: z.array(vec).max(1100),
  spawn: vec,
  state: z.enum(["idle", "walk", "attack", "cast", "dead"]),
  stateUntil: z.number().int().nonnegative(),
  targetId: z.string().nullable(),
  cooldowns: z.record(z.string(), z.number().nonnegative()),
  respawnAt: z.number().int().nonnegative(),
  nextAttack: z.number().int().nonnegative(),
  phase: z.number().int().nonnegative(),
  facing: z.number(),
  autoAttack: z.boolean(),
});
export const legacySnapshotSchema = z.object({
  schemaVersion: z.literal(1),
  contentVersion: z.literal("0.1.0"),
  characterId: z.string().min(1).max(120),
  playerId: z.string(),
  tick: z.number().int().nonnegative(),
  rngState: z.number().int().nonnegative(),
  nextId: z.number().int().nonnegative(),
  mapId: z.string(),
  entities: z.record(z.string(), entity),
  name: z.string().trim().min(2).max(18),
  classId: z.string(),
  appearance: z.enum(["male", "female"]),
  level: z.number().int().min(1).max(60),
  experience: z.number().nonnegative(),
  attributes: z.object({
    strength: z.number().int().min(0).max(10000),
    dexterity: z.number().int().min(0).max(10000),
    vitality: z.number().int().min(0).max(10000),
    energy: z.number().int().min(0).max(10000),
  }),
  attributePoints: z.number().int().nonnegative(),
  skillPoints: z.number().int().nonnegative(),
  skillLevels: z.record(z.string(), z.number().int().min(0).max(5)),
  inventory: z.array(item).max(32),
  equipment: z.record(z.string(), item),
  quests: z.array(
    z.object({
      id: z.string(),
      status: z.enum(["active", "ready", "claimed"]),
      progress: z.number().int().nonnegative(),
    }),
  ),
  gold: z.number().int().nonnegative(),
  settings: z.object({
    sound: z.boolean(),
    music: z.boolean(),
    effects: z.enum(["high", "low"]),
    fps: z.union([z.literal(30), z.literal(60)]),
  }),
  pendingInteraction: z.string().nullable(),
});
