import { z } from "zod";
export const statusApplicationSchema = z.object({
  kind: z.enum([
    "poison",
    "burn",
    "regen",
    "slow",
    "stun",
    "freeze",
    "silence",
    "shield",
    "armorBreak",
    "haste",
    "attackBuff",
    "defenseBuff",
    "vampirism",
    "invulnerable",
  ]),
  durationTicks: z.number().int().positive(),
  magnitude: z.number().nonnegative(),
  intervalTicks: z.number().int().positive().optional(),
  maxStacks: z.number().int().min(1).max(5).optional(),
});
export const skillSchema = z.object({
  id: z.string(),
  name: z.string(),
  icon: z.string(),
  kind: z.enum([
    "melee",
    "line",
    "aoe",
    "heal",
    "buff",
    "projectile",
    "cone",
    "dash",
    "passive",
  ]),
  cooldownTicks: z.number().int().nonnegative(),
  manaCost: z.number().nonnegative(),
  range: z.number().positive(),
  power: z.number().positive(),
  requiredLevel: z.number().int().min(1).max(100),
  maxLevel: z.number().int().min(1).max(10),
  description: z.string(),
  classId: z.string().optional(),
  branchId: z.string().optional(),
  element: z.enum(["metal", "wood", "water", "fire", "earth"]).optional(),
  castTicks: z.number().int().nonnegative().default(0),
  projectileSpeed: z.number().positive().default(8),
  areaRadius: z.number().positive().default(2),
  pierce: z.number().int().min(0).max(8).default(0),
  lifeSteal: z.number().min(0).max(1).default(0),
  effects: z.array(statusApplicationSchema).default([]),
  passive: z
    .object({
      attack: z.number().default(0),
      defense: z.number().default(0),
      maxHp: z.number().default(0),
      maxMp: z.number().default(0),
      lifeSteal: z.number().default(0),
      critChance: z.number().default(0),
      accuracy: z.number().default(0),
      evasion: z.number().default(0),
      resistance: z.number().default(0),
    })
    .optional(),
});
export type SkillDefinition = z.infer<typeof skillSchema>;
